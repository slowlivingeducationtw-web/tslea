  '慢活文字專欄｜每月一味': { full: 'Slow Living in Words | A Scent a Month', short: 'A Scent a Month' },
  '慢活文字專欄｜每月一遊': { full: 'Slow Living in Words | A Journey a Month', short: 'A Journey a Month' },
